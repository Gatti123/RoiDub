export const dict: Record<Lang, Dict> = { en, ru };
export type DictKey = keyof Dict;

export function t(lang: Lang, key: DictKey | string, vars?: Record<string, string | number>) {
  const d = dict[lang] as Record<string, string>;
  let s = d[key] ?? (dict.en as Record<string, string>)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function fmtMoney(n: number, lang: Lang) {
  return new Intl.NumberFormat(lang === "ru" ? "ru-RU" : "en-US", { maximumFractionDigits: 0 }).format(Math.round(n)) + " AED";
}
export function fmtNum(n: number, lang: Lang) {
  return new Intl.NumberFormat(lang === "ru" ? "ru-RU" : "en-US", { maximumFractionDigits: 0 }).format(Math.round(n));
}
export function fmtPct(n: number | null | undefined, lang: Lang, digits = 1) {
  if (n === null || n === undefined || !isFinite(n)) return "—";
  return new Intl.NumberFormat(lang === "ru" ? "ru-RU" : "en-US", { maximumFractionDigits: digits, minimumFractionDigits: digits }).format(n) + "%";
}
